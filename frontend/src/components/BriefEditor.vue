<script setup lang="ts">
import { reactive, ref, watch } from 'vue'
import type { BriefContent } from '../api/types'
import AiLabel from './AiLabel.vue'
import { arrayToLines, linesToArray } from '../utils'

const props = defineProps<{ content: BriefContent; version: number; busy: boolean; source: 'ai' | 'sender' }>()
const emit = defineEmits<{ save: [BriefContent] }>()

const form = reactive({ progress: '', decisions: '', remaining: '', blockers: '', gaps: '' })
const refs = ref<{ url: string; title: string; note: string }[]>([])
const error = ref<string | null>(null)

function reset() {
  const c = props.content
  form.progress = c.progress
  form.decisions = arrayToLines(c.decisions)
  form.remaining = arrayToLines(c.remaining_tasks)
  form.blockers = arrayToLines(c.blockers)
  form.gaps = arrayToLines(c.gaps)
  refs.value = c.references.map((r) => ({ url: r.url, title: r.title ?? '', note: r.note ?? '' }))
  error.value = null
}
watch(() => props.version, reset, { immediate: true })

function submit() {
  if (!form.progress.trim()) {
    error.value = 'Progress cannot be empty.'
    return
  }
  error.value = null
  emit('save', {
    progress: form.progress.trim(),
    decisions: linesToArray(form.decisions),
    remaining_tasks: linesToArray(form.remaining),
    blockers: linesToArray(form.blockers),
    gaps: linesToArray(form.gaps),
    references: refs.value
      .filter((r) => r.url.trim())
      .map((r) => ({ url: r.url.trim(), title: r.title.trim() || null, note: r.note.trim() || null })),
  })
}
</script>

<template>
  <form class="card" aria-labelledby="edit-h" @submit.prevent="submit">
    <h2 id="edit-h">Edit brief <AiLabel v-if="source === 'ai'" /></h2>
    <p class="hint">This draft was generated by AI and may contain mistakes. Correct it before approving. Saving creates a new version.</p>
    <label for="b-progress">Progress</label>
    <textarea id="b-progress" v-model="form.progress" required></textarea>
    <label for="b-dec">Decisions <span class="hint">(one per line)</span></label>
    <textarea id="b-dec" v-model="form.decisions"></textarea>
    <label for="b-rem">Remaining tasks <span class="hint">(one per line)</span></label>
    <textarea id="b-rem" v-model="form.remaining"></textarea>
    <label for="b-blk">Blockers <span class="hint">(one per line)</span></label>
    <textarea id="b-blk" v-model="form.blockers"></textarea>
    <fieldset style="margin-top:.75rem">
      <legend><strong>References</strong></legend>
      <div v-for="(r, i) in refs" :key="i" class="refrow">
        <input v-model="r.url" type="text" :aria-label="`Reference ${i + 1} URL`" placeholder="URL" />
        <input v-model="r.title" type="text" :aria-label="`Reference ${i + 1} title`" placeholder="Title" />
        <input v-model="r.note" type="text" :aria-label="`Reference ${i + 1} note`" placeholder="Note" />
        <button type="button" :aria-label="`Remove reference ${i + 1}`" @click="refs.splice(i, 1)">Remove</button>
      </div>
      <button type="button" @click="refs.push({ url: '', title: '', note: '' })">Add reference</button>
    </fieldset>
    <label for="b-gaps">Gaps <span class="hint">(one per line; remove ones you have resolved)</span></label>
    <textarea id="b-gaps" v-model="form.gaps"></textarea>
    <p v-if="error" class="field-error" role="alert">{{ error }}</p>
    <div class="row">
      <button type="submit" class="primary" :disabled="busy" data-test="save-brief">Save edits</button>
      <button type="button" :disabled="busy" @click="reset">Discard changes</button>
    </div>
  </form>
</template>
