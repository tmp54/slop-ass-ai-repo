<script setup lang="ts">
import { computed, onBeforeUnmount, ref, watch } from 'vue'
import { useHandoffStore } from '../stores/handoff'
import { useSessionStore } from '../stores/session'
import StatusStepper from '../components/StatusStepper.vue'
import BriefView from '../components/BriefView.vue'
import BriefEditor from '../components/BriefEditor.vue'
import QuestionsPanel from '../components/QuestionsPanel.vue'
import RestatementPanel from '../components/RestatementPanel.vue'
import SenderActions from '../components/SenderActions.vue'
import HistoryList from '../components/HistoryList.vue'
import ErrorAlert from '../components/ErrorAlert.vue'
import type { BriefContent } from '../api/types'

const props = defineProps<{ id: number }>()
const store = useHandoffStore()
const session = useSessionStore()
const editing = ref(false)

const d = computed(() => store.detail)
const isSender = computed(() => session.role === 'sender')

watch(
  () => props.id,
  async (id) => {
    store.reset()
    editing.value = false
    await store.load(id)
    store.startPolling(id)
  },
  { immediate: true },
)
onBeforeUnmount(() => store.reset())

async function save(c: BriefContent) {
  if (await store.saveBrief(c)) editing.value = false
}
async function approve() {
  await store.approve()
}
</script>

<template>
  <p><RouterLink to="/handoffs">Back to handoffs</RouterLink></p>
  <p v-if="store.loading && !d" role="status">Loading...</p>
  <ErrorAlert v-if="!d" :message="store.errorMessage">
    <button type="button" @click="store.load(id)">Retry</button>
  </ErrorAlert>

  <template v-if="d">
    <h1>{{ d.title }}</h1>
    <StatusStepper :state="d.state" :poll-error="store.pollError" />

    <ErrorAlert :message="store.errorMessage">
      <button v-if="store.aiUnavailable && isSender" type="button" data-test="retry-draft"
              :disabled="store.busy" @click="store.redraft()">Retry AI draft</button>
    </ErrorAlert>

    <details class="card">
      <summary>Sender's original notes and links</summary>
      <p style="white-space:pre-wrap">{{ d.notes }}</p>
      <ul v-if="d.links.length" class="plain">
        <li v-for="l in d.links" :key="l"><a :href="l" target="_blank" rel="noopener noreferrer">{{ l }}</a></li>
      </ul>
    </details>

    <!-- SENDER -->
    <template v-if="isSender">
      <section v-if="d.state === 'submitted'" class="card" data-test="draft-missing">
        <h2>AI draft not available</h2>
        <p>The AI draft has not been produced yet or it failed. Nothing is lost; you can retry.</p>
        <div class="row">
          <button type="button" class="primary" data-test="retry-draft-main" :disabled="!store.can('draft')" @click="store.redraft()">
            {{ store.busy ? 'Drafting...' : 'Draft brief with AI' }}
          </button>
        </div>
      </section>

      <template v-if="d.brief">
        <BriefView :brief="d.brief" />
        <section v-if="d.state === 'ai_drafted'" class="card" aria-labelledby="rv-h">
          <h2 id="rv-h">Review the AI draft</h2>
          <p>The brief above was generated by AI. Review it, edit anything that is wrong, then approve to share it with the receiver.</p>
          <div class="row">
            <button type="button" :disabled="!store.can('edit_brief')" data-test="edit" @click="editing = !editing">
              {{ editing ? 'Hide editor' : 'Edit brief' }}
            </button>
            <button type="button" :disabled="!store.can('draft')" data-test="redraft" @click="store.redraft()">Redraft with AI (replaces current draft)</button>
            <button type="button" class="primary" :disabled="!store.can('approve')" data-test="approve" @click="approve">
              {{ store.busy ? 'Working...' : 'Approve and send to receiver' }}
            </button>
          </div>
        </section>
        <BriefEditor v-if="editing && store.can('edit_brief')" :content="d.brief.content" :version="d.brief.version"
                     :source="d.brief.source" :busy="store.busy" @save="save" />
      </template>

      <RestatementPanel v-if="d.restatements.length" />
      <QuestionsPanel v-if="d.questions.length" />
      <SenderActions />
    </template>

    <!-- RECEIVER -->
    <template v-else>
      <section v-if="!d.brief" class="card" data-test="brief-pending">
        <h2>Brief not available yet</h2>
        <p>The sender has not approved the brief. This page updates automatically.</p>
      </section>
      <template v-else>
        <BriefView :brief="d.brief" />
        <RestatementPanel />
        <QuestionsPanel />
      </template>
    </template>

    <HistoryList :transitions="d.transitions" />
  </template>
</template>
